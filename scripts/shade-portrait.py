#!/usr/bin/env python3
"""
Attach a light-mode shade class to every point of the shipped dot portrait.

Run:  python3 scripts/shade-portrait.py
Writes: src/data/portrait-shade.ts

Companion to scripts/gen-portrait.py, which draws the ALTERNATIVE photo-derived
cloud. This script never touches the shipped point cloud — it only reads it.
"""
import re, json
from pathlib import Path
from PIL import Image
import numpy as np

ROOT = Path(__file__).resolve().parent.parent

src = open(ROOT / 'src/data/portrait.ts').read()
data = json.loads('{' + re.search(r'\{("w".*)\};', src, re.S).group(1) + '}')
d = data['d']
im = Image.open(ROOT / 'public/icon.webp').convert('RGB')
W, H = im.size
a = np.asarray(im, float) / 255.0
V = a.max(2)
S = (a.max(2) - a.min(2)) / np.maximum(a.max(2), 1e-6)

# The photo is a backlit studio portrait with a hole blown through the middle:
# the brightest thing in the frame is NOT the backdrop behind the shoulders, it
# is the lit FACE (V~0.93). The backdrop behind the head sits at V~0.70 and the
# shoulders at V~0.68, with the same saturation. A plain "bright = skin" test
# therefore paints the wall as face and leaves the actual face unclassified —
# which is what happened: the big solid dots in the middle of the head were
# backdrop showing through between the hair, and they stayed the default ink.
#
# So three tests, in order:
#   1. dark      V < DARK_V                          -> hair or shirt
#   2. skin      warm (sat > SKIN_S) AND mid/normal  -> the face, anywhere
#   3. backdrop  V in the wall/haze band, low sat    -> the wall seen through
DARK_V = 0.25
SKIN_S = 0.20
BACKDROP_S = 0.16
BACKDROP_LO, BACKDROP_HI = 0.55, 0.80

rows = []
for x, y, s in d:
    px = min(W - 1, int(x / data['w'] * W))
    py = min(H - 1, int(y / data['h'] * H))
    v, sat = V[py, px], S[py, px]
    if v < DARK_V:
        k = '1'                                  # hair / shirt
    elif sat > SKIN_S and BACKDROP_LO <= v <= 1:
        k = '2'                                  # lit face
    elif sat <= BACKDROP_S and BACKDROP_LO <= v <= BACKDROP_HI:
        k = '2'                                  # backdrop seen through
    else:
        k = '0'
    rows.append(f'"{x:g},{y:g}":{k}')

total = len(rows)
hair = sum(1 for r in rows if r.endswith(':1'))
star = sum(1 for r in rows if r.endswith(':2'))
print(total, hair, star)
body = ','.join(rows)
out = (
    "/* AUTO-GENERATED by scripts/shade-portrait.py — do not edit by hand.\n"
    "   Regenerate with: python3 scripts/shade-portrait.py\n"
    "\n"
    "   The shipped point cloud (src/data/portrait.ts, restored byte-for-byte\n"
    "   from d5a99fa) carries only x, y and size, so every dot is painted the\n"
    "   same colour. That is correct in dark mode — white dots on near-black\n"
    "   are the portrait. In light mode it collapses into a flat black blob:\n"
    "   hair, face and shirt all read as one shape.\n"
    "\n"
    "   This file adds a single extra field per point, sampled from the photo\n"
    "   in public/icon.webp at the point's own position:\n"
    "\n"
    "     0  skin / backdrop  -> keeps the normal dot colour\n"
    "     1  hair and shirt   -> painted darker in light mode\n"
    "     2  lit skin         -> painted lighter in light mode (the face)\n"
    "        and the backdrop seen through the hair, which would otherwise be\n"
    "        a solid block of the default ink right where the face should be\n"
    "\n"
    "   The split is by VALUE not luminance: hair and shirt sit at V<0.25 at\n"
    "   saturation ~0.2, while the backdrop is V~0.7 at a similar saturation,\n"
    "   so a plain brightness test paints the wall as skin. The face is warm\n"
    f"   (saturation > {SKIN_S}); the wall seen through the hair is not. Counts: {total} points, {hair} hair/shirt, {star} face/backdrop.\n"
    "   Nothing else is derived from the photo — no position or size is touched,\n"
    "   so the shape the owner approved is exactly the one still rendered. */\n"
    "export type PortraitShade = 0 | 1 | 2;\n"
    "\n"
    "/** key `x,y` (grid units) -> shade class. */\n"
    f"export const PORTRAIT_SHADE: Record<string, PortraitShade> = {{{body}}};\n"
)
open(ROOT / 'src/data/portrait-shade.ts', 'w').write(out)
print('wrote', len(out))
